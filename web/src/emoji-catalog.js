const entries = emojiCatalog
  .filter(row => Array.isArray(row) && row.length >= 2)
  .map(([emoji, name, keywords]) => ({ emoji, name, haystack: `${name} ${keywords || ''}`.toLowerCase() }))

export function searchEmojiCatalog(query, limit = 48) {
  const term = String(query || '').trim().toLowerCase()
  if (!term) return []
  return entries.filter(entry => entry.haystack.includes(term)).slice(0, limit)
}
